#!/usr/bin/env node
// tokens.json (DTCG) -> tokens.css. Node >= 18, no dependencies.
//   node design/build-tokens.mjs            writes design/tokens.css
//   node design/build-tokens.mjs --check    exit 1 if tokens.css is out of date (use in CI)
// Semantic tokens carry the light value in $value and the dark value in $extensions.mode.dark.
// Aliases {a.b.c} become var(--a-b-c), so product code only sees semantic and component names.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const tree = JSON.parse(fs.readFileSync(path.join(dir, 'tokens.json'), 'utf8'));
const cssName = (trail) => '--' + trail.join('-');
const toCss = (v) => (typeof v === 'string' ? v.replace(/\{([^}]+)\}/g, (_, ref) => `var(${cssName(ref.split('.'))})`) : String(v));

const light = [];
const dark = [];
const walk = (node, trail) => {
  if (node && typeof node === 'object' && '$value' in node) {
    light.push(`  ${cssName(trail)}: ${toCss(node.$value)};`);
    const d = node.$extensions?.mode?.dark;
    if (d !== undefined) dark.push(`  ${cssName(trail)}: ${toCss(d)};`);
    return;
  }
  for (const [k, v] of Object.entries(node || {})) if (!k.startsWith('$')) walk(v, [...trail, k]);
};
walk(tree, []);

const css = [
  '/* Generated by design/build-tokens.mjs from design/tokens.json. Do not edit by hand. */',
  ':root {', ...light, '  color-scheme: light;', '}',
  '@media (prefers-color-scheme: dark) {', '  :root:not([data-theme="light"]) {', ...dark.map((l) => '  ' + l), '    color-scheme: dark;', '  }', '}',
  ':root[data-theme="dark"] {', ...dark, '  color-scheme: dark;', '}',
  '',
].join('\n');

const out = path.join(dir, 'tokens.css');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (current !== css) { console.error('tokens.css is out of date: run node design/build-tokens.mjs'); process.exit(1); }
  console.log('tokens.css is up to date');
} else {
  fs.writeFileSync(out, css);
  console.log(`wrote ${out} (${light.length} tokens, ${dark.length} dark overrides)`);
}
